# -*- coding: utf-8 -*-
"""Execute a notebook in place using nbclient with an explicit kernelspec.

The `jupyter` CLI is unavailable here (no console scripts were generated by the
offline wheel install), so use the Python API directly.
"""
import json
import os
import sys
from contextlib import contextmanager

# --- sandbox workaround -------------------------------------------------
# jupyter_core.paths.secure_write() sets an explicit ACL on the connection
# file, which the DSH file sandbox denies (WinError 5 / Errno 13).  The file
# only needs to be readable by the kernel process we start ourselves, so fall
# back to a plain UTF-8 write.  Patch BEFORE importing jupyter_client.
import jupyter_core.paths as _jp


@contextmanager
def _plain_write(filename, mode=0o600):
    directory = os.path.dirname(os.path.abspath(filename))
    if directory:
        os.makedirs(directory, exist_ok=True)
    fd = os.open(filename, os.O_WRONLY | os.O_CREAT | os.O_TRUNC)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            yield f
    except Exception:
        try:
            os.unlink(filename)
        except OSError:
            pass
        raise


_jp.secure_write = _plain_write
sys.modules["jupyter_core.paths"].secure_write = _plain_write
# ------------------------------------------------------------------------

import nbformat
from nbclient import NotebookClient
from jupyter_client.kernelspec import KernelSpec, KernelSpecManager

NOTEBOOK = sys.argv[1]
PYEXE = sys.argv[2]

ks = {
    "argv": [PYEXE, "-m", "ipykernel_launcher", "-f", "{connection_file}"],
    "display_name": "Python (exp01)",
    "language": "python",
}


class FixedKSM(KernelSpecManager):
    """Report our offline kernelspec for the names the notebook asks for."""

    def get_kernel_spec(self, kernel_name):
        if kernel_name in ("exp01", "python3"):
            return KernelSpec(
                argv=ks["argv"],
                resources={},
                display_name=ks["display_name"],
                language=ks["language"],
                metadata={},
            )
        return super().get_kernel_spec(kernel_name)


nb = nbformat.read(NOTEBOOK, as_version=4)
client = NotebookClient(
    nb,
    timeout=300,
    kernel_name="exp01",
    resources={"metadata": {"path": os.path.dirname(os.path.abspath(NOTEBOOK))}},
)
client.kernel_spec_manager = FixedKSM()

client.execute()
with open(NOTEBOOK, "w", encoding="utf-8", newline="\n") as fh:
    nbformat.write(nb, fh, version=4)

n_err = 0
n_code = 0
for c in nb.cells:
    if c.cell_type != "code":
        continue
    n_code += 1
    for o in c.get("outputs", []):
        if o.get("output_type") == "error":
            n_err += 1
            print(f"ERROR in cell: {o.get('ename')}: {o.get('evalue')}")
print(f"executed {n_code} code cells, {n_err} errors -> {NOTEBOOK}")
sys.exit(1 if n_err else 0)
